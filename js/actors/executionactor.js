// ============================================================
// §3 — Task settlement (into the flow)
// ============================================================
//
// @proposal=P-ACTOR-FLOW-002 — SETTLETASK returns { ENV, RESPONSE }.
// It does NOT emit SENDRESPONSE. It resolves the task's settle signal
// so AWAITTASK's promises resolve. The dispatcher emits the ONE response
// owed to EXECUTEELEMENT's caller.

function SETTLETASK(TASKID, STATUS, RESULT, ERROR, ENV) {
  logdebug(ENV, '[EXECUTIONACTOR]', 'SETTLETASK TASK:', TASKID, 'STATUS:', STATUS);
  var NEXTENV = {};
  Object.keys(ENV || {}).forEach(function(K) { NEXTENV[K] = ENV[K]; });
  var EXECSLICE = NEXTENV.execution;
  if (!EXECSLICE) {
    NEXTENV = ENSUREEXECUTIONSLICE(NEXTENV);
    EXECSLICE = NEXTENV.execution;
  }
  var TASK = EXECSLICE.TASKS[TASKID];
  if (!TASK) return { ENV: NEXTENV, RESPONSE: undefined };

  TASK.STATUS = STATUS;
  TASK.RESULT = RESULT || null;
  TASK.ERROR = ERROR || null;

  var RESPONSEPAYLOAD = null;
  if (STATUS === 'EXECUTED') {
    RESPONSEPAYLOAD = { TASKID: TASKID, PIPELINEID: TASK.PIPELINEID, ELEMENTID: TASK.ELEMENTID, RESULT: RESULT || {} };
    SENDINSTRUCTION('BROADCAST', MESSAGETYPES.BLOCKEXECUTED, {
      PIPELINEID: TASK.PIPELINEID || null, STAGEPATH: TASK.STAGEPATH || null,
      ELEMENTID: TASK.ELEMENTID || null, TOKEN: TASK.TOKEN || null, RESULT: RESULT || {}
    }, GENERATETAG(), 'EXECUTIONACTOR');
  } else if (STATUS === 'FAILED') {
    RESPONSEPAYLOAD = {
      TASKID: TASKID, PIPELINEID: TASK.PIPELINEID, ELEMENTID: TASK.ELEMENTID,
      ERROR: { MESSAGE: ERROR ? ERROR.message : 'TASK FAILED', DIAGNOSTIC: (ERROR && ERROR.diagnostic) ? ERROR.diagnostic : {} }
    };
    SENDINSTRUCTION('BROADCAST', MESSAGETYPES.BLOCKFAILED, {
      PIPELINEID: TASK.PIPELINEID || null, STAGEPATH: TASK.STAGEPATH || null,
      ELEMENTID: TASK.ELEMENTID || null, TOKEN: TASK.TOKEN || null,
      ERROR: ERROR ? ERROR.message : 'TASK FAILED', DIAGNOSTIC: (ERROR && ERROR.diagnostic) ? ERROR.diagnostic : {}
    }, GENERATETAG(), 'EXECUTIONACTOR');
  }

  TASK.CONSUMERS = [];
  if (TASK.SETTLE_SIGNAL && TASK.SETTLE_SIGNAL.RESOLVE) {
    TASK.SETTLE_SIGNAL.RESOLVE({ STATUS: STATUS, RESULT: TASK.RESULT, ERROR: TASK.ERROR });
    TASK.SETTLE_SIGNAL.RESOLVE = null;
  }
  SENDEXECUTIONUPDATE(EXECSLICE);
  logdebug(ENV, '[EXECUTIONACTOR]', 'SETTLETASK COMPLETED:', TASKID);

  return { ENV: NEXTENV, RESPONSE: RESPONSEPAYLOAD };
}

// @proposal=P-ACTOR-FLOW-002 — returns Promise<{ENV, RESPONSE}>. No
// out-of-flow state publication: the resolution IS the settlement.
function RUNELEMENTTASK(TASKID, DESCRIPTOR, ENV) {
  var EXECUTIONCONTEXT = {
    ENV: DESCRIPTOR.ENV || {},
    INPUTS: (DESCRIPTOR.SIGNATURE && (DESCRIPTOR.SIGNATURE.inputs || DESCRIPTOR.SIGNATURE.INPUTS)) || [],
    OUTPUTS: (DESCRIPTOR.SIGNATURE && (DESCRIPTOR.SIGNATURE.outputs || DESCRIPTOR.SIGNATURE.OUTPUTS)) || {},
    PROPERTIES: DESCRIPTOR.PROPERTIES || {}
  };
  logdebug(ENV, '[EXECUTIONACTOR]', 'RUNELEMENTTASK START:', TASKID, DESCRIPTOR.ELEMENTID, 'PIPELINE:', DESCRIPTOR.PIPELINEID);
  var EXECUTOR = DESCRIPTOR.EXECUTOR;
  if (typeof EXECUTOR !== 'function') {
    var FAILUREERROR = new Error('[EXECUTIONACTOR] DESCRIPTOR.EXECUTOR is not a function');
    return Promise.resolve(SETTLETASK(TASKID, 'FAILED', null, FAILUREERROR, ENV));
  }
  var EXECUTIONPROMISE;
  try {
    EXECUTIONPROMISE = Promise.resolve(EXECUTOR(EXECUTIONCONTEXT));
  } catch (SYNCERR) {
    EXECUTIONPROMISE = Promise.reject(SYNCERR);
  }
  return EXECUTIONPROMISE.then(function(RESULT) {
    logdebug(ENV, '[EXECUTIONACTOR]', 'RUNELEMENTTASK COMPLETED:', TASKID, DESCRIPTOR.ELEMENTID);
    return SETTLETASK(TASKID, 'EXECUTED', RESULT || {}, null, ENV);
  }).catch(function(ERR) {
    logerror(ENV, '[EXECUTIONACTOR]', 'RUNELEMENTTASK FAILED:', TASKID, DESCRIPTOR.ELEMENTID, ERR);
    return SETTLETASK(TASKID, 'FAILED', null, ERR, ENV);
  });
}

