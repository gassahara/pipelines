function EXECUTIONBEHAVIORCCCRETRY(ENV, ARGS) {
  logdebug(ENV, '[EXECUTIONACTOR]', 'ACTION CCCRETRY PIPELINE:', ARGS.PIPELINEID, 'ELEMENT:', ARGS.ELEMENTID);
  var RETRYCONTINUATION = ARGS.CONTINUATION;
  if (!RETRYCONTINUATION || typeof RETRYCONTINUATION.FN !== 'function') {
    return { ENV: ENV, RESPONSE: { ERROR: 'cccretry: no continuation' } };
  }
  var RETRYRESULT;
  try {
    RETRYRESULT = RETRYCONTINUATION.FN.apply(null, RETRYCONTINUATION.ARGS || []);
  } catch (SYNCERR) {
    return { ENV: ENV, RESPONSE: { ERROR: SYNCERR && SYNCERR.message ? SYNCERR.message : String(SYNCERR) } };
  }
  return Promise.resolve(RETRYRESULT).then(function(SETTLED) {
    return { ENV: ENV, RESPONSE: SETTLED || {} };
  }).catch(function(RETRYERR) {
    return { ENV: ENV, RESPONSE: { ERROR: RETRYERR && RETRYERR.message ? RETRYERR.message : String(RETRYERR) } };
  });
}

