function EXECUTIONBEHAVIORAWAITTASK(ENV, ARGS) {
  var NEXTENV = ENSUREEXECUTIONSLICE(ENV);
  var EXECSLICE = NEXTENV.execution;
  logdebug(ENV, '[EXECUTIONACTOR]', 'ACTION AWAITTASK TASK:', ARGS.TASKID);
  var TASK = EXECSLICE.TASKS[ARGS.TASKID];
  if (!TASK) {
    var INDEXED = EXECSLICE.TASKINDEX ? EXECSLICE.TASKINDEX[ARGS.TASKID] : null;
    if (INDEXED) {
      var RECHECK = (INDEXED.STATUS === 'FAILED' || INDEXED.STATUS === 'CANCELLED' || INDEXED.STATUS === 'STOPPED')
        ? { TASKID: INDEXED.TASKID, PIPELINEID: INDEXED.PIPELINEID, ELEMENTID: INDEXED.ELEMENTID, ERROR: 'Task settled: ' + INDEXED.STATUS }
        : { TASKID: INDEXED.TASKID, PIPELINEID: INDEXED.PIPELINEID, ELEMENTID: INDEXED.ELEMENTID, RESULT: null };
      return { ENV: NEXTENV, RESPONSE: RECHECK };
    }
    return { ENV: NEXTENV, RESPONSE: { ERROR: '[EXECUTIONACTOR] UNKNOWN TASK: ' + ARGS.TASKID } };
  }
  if (TASK.STATUS === 'EXECUTED') {
    return { ENV: NEXTENV, RESPONSE: TASK.RESULT || {} };
  }
  if (TASK.STATUS === 'FAILED') {
    return { ENV: NEXTENV, RESPONSE: { ERROR: TASK.ERROR ? TASK.ERROR.message : 'TASK FAILED' } };
  }
  if (TASK.STATUS === 'CANCELLED') {
    return { ENV: NEXTENV, RESPONSE: { ERROR: TASK.ERROR ? TASK.ERROR.message : 'TASK CANCELLED' } };
  }
  if (TASK.STATUS === 'STOPPED') {
    return { ENV: NEXTENV, RESPONSE: { ERROR: 'TASK STOPPED' } };
  }
  // Pending: chain off the settle signal.
  var CAPTURED_ENV = NEXTENV;
  return TASK.SETTLE_SIGNAL.PROMISE.then(function(SETTLEMENT) {
    if (SETTLEMENT.STATUS === 'EXECUTED') return { ENV: CAPTURED_ENV, RESPONSE: SETTLEMENT.RESULT || {} };
    return { ENV: CAPTURED_ENV, RESPONSE: { ERROR: SETTLEMENT.ERROR && SETTLEMENT.ERROR.message ? SETTLEMENT.ERROR.message : ('TASK ' + SETTLEMENT.STATUS) } };
  });
}

function EXECUTIONBEHAVIORGETTASKS(ENV, ARGS) {
  var NEXTENV = ENSUREEXECUTIONSLICE(ENV);
  var EXECSLICE = NEXTENV.execution;
  var RESULT = [];
  Object.keys(EXECSLICE.TASKS).forEach(function(TID) {
    var T = EXECSLICE.TASKS[TID];
    if (ARGS.PIPELINEID && T.PIPELINEID !== ARGS.PIPELINEID) return;
    if (ARGS.ELEMENTID && T.ELEMENTID !== ARGS.ELEMENTID) return;
    if (ARGS.KIND && T.KIND !== ARGS.KIND) return;
    RESULT.push({ TASKID: T.TASKID, KIND: T.KIND, PIPELINEID: T.PIPELINEID, ELEMENTID: T.ELEMENTID, PARENTTASKID: T.PARENTTASKID, STATUS: T.STATUS, ORIGIN: T.ORIGIN, PROGRAMREF: T.PROGRAMREF, SERIALIZED: T.SERIALIZED, CONSUMERCOUNT: (T.CONSUMERS || []).length });
  });
  if (EXECSLICE.TASKINDEX) {
    Object.keys(EXECSLICE.TASKINDEX).forEach(function(TID) {
      var T = EXECSLICE.TASKINDEX[TID];
      if (ARGS.PIPELINEID && T.PIPELINEID !== ARGS.PIPELINEID) return;
      if (ARGS.ELEMENTID && T.ELEMENTID !== ARGS.ELEMENTID) return;
      if (ARGS.KIND && T.KIND !== ARGS.KIND) return;
      RESULT.push({ TASKID: T.TASKID, KIND: T.KIND, PIPELINEID: T.PIPELINEID, ELEMENTID: T.ELEMENTID, PARENTTASKID: T.PARENTTASKID, STATUS: T.STATUS, ORIGIN: T.ORIGIN, PROGRAMREF: T.PROGRAMREF, SERIALIZED: null, CONSUMERCOUNT: 0 });
    });
  }
  return { ENV: NEXTENV, RESPONSE: RESULT };
}

