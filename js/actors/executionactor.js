function EXECUTIONBEHAVIORTASKSETTLED(ENV, ARGS) {
  var NEXTENV = ENSUREEXECUTIONSLICE(ENV);
  var EXECSLICE = NEXTENV.execution;
  logdebug(ENV, '[EXECUTIONACTOR]', 'ACTION TASKSETTLED TASK:', ARGS.TASKID, 'STATUS:', ARGS.STATUS);
  var TASK4 = EXECSLICE.TASKS[ARGS.TASKID];
  if (TASK4) {
    TASK4.STATUS = ARGS.STATUS;
    TASK4.RESULT = ARGS.RESULT || null;
    TASK4.ERROR = ARGS.ERROR || null;
    if (TASK4.SETTLE_SIGNAL && TASK4.SETTLE_SIGNAL.RESOLVE) {
      TASK4.SETTLE_SIGNAL.RESOLVE({ STATUS: ARGS.STATUS, RESULT: ARGS.RESULT || null, ERROR: ARGS.ERROR || null });
      TASK4.SETTLE_SIGNAL.RESOLVE = null;
    }
    TASK4.CONSUMERS = [];
    SENDEXECUTIONUPDATE(EXECSLICE);
  }
  return NEXTENV;
}

function EXECUTIONBEHAVIORRECOVER(ENV, ARGS) {
  return DBRESTORE('actor:state:execution').then(function(SAVED) {
    var NEXTENV = {};
    Object.keys(ENV).forEach(function(K) { NEXTENV[K] = ENV[K]; });
    NEXTENV.EXECUTION = (SAVED !== null && SAVED !== undefined) ? SAVED : { PIPELINES: {}, TASKS: {}, TASKORDER: [], TASKINDEX: {}, TASKCOUNTER: 0, HTMLSNAPSHOT: null };
    SENDEXECUTIONUPDATE(NEXTENV.EXECUTION);
    return { ENV: NEXTENV, RESPONSE: NEXTENV };
  }).catch(function(E) {
    return ENV;
  });
}

