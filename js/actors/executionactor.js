function EXECUTIONBEHAVIOR(ENV, MESSAGE) {
  var OUT = INVOKEHANDLER('EXECUTIONACTOR', ENV, MESSAGE);
  if (OUT.matched !== true) return ENV;
  return OUT.result;
}

