// @proposal=P-ACTOR-FLOW-002 — orchestratestage mutates its env argument
// in place (via createpersistentelementwrapper). This handler wraps the
// result in a fresh ENV before returning so the world map receives a
// distinct object.
function HYPERVISORBEHAVIOREVENTTRIGGERED(ENV, ARGS) {
  if (!ARGS.STAGE) {
    logwarn(ENV, '[HYPERVISOR]', 'EVENTTRIGGERED received without STAGE; no walk performed',
      'PIPELINEID:', ARGS.PIPELINEID, 'STAGEID:', ARGS.STAGEID);
    return ENV;
  }
  return orchestratestage(
    ARGS.STAGE,
    ARGS.PIPELINEID || 'event',
    ARGS.ENV || {},
    ARGS.STAGEPATH || [],
    ARGS.OPTIONS || {},
    true
  ).then(function(RESOLVED) {
    var NEXTENV = {};
    Object.keys(RESOLVED || {}).forEach(function(K) { NEXTENV[K] = RESOLVED[K]; });
    return NEXTENV;
  });
}

function HYPERVISORBEHAVIORPING(ENV, ARGS) {
  return { ENV: ENV, RESPONSE: true };
}

function HYPERVISORBEHAVIORRECOVER(ENV, ARGS) {
  return DBRESTORE('actor:state:hypervisor').then(function(SAVED) {
    var NEXTENV = {};
    Object.keys(ENV).forEach(function(K) { NEXTENV[K] = ENV[K]; });
    NEXTENV.HYPERVISOR = (SAVED && typeof SAVED === 'object') ? SAVED : {
      BOOT: true, ENVBYPIPELINE: {}, RENDERHTML: '', EXECUTIONSTACK: [],
      ROUTES: {}, ACTIVEPIPELINES: [], PROGRAMS: {}
    };
    SENDINSTRUCTION('WORLDMAPACTOR', 'UPDATE', {
      UPDATES: [{ PATH: 'HYPERVISOR', VALUE: NEXTENV.HYPERVISOR }]
    }, GENERATETAG(), 'HYPERVISORACTOR');
    return { ENV: NEXTENV, RESPONSE: NEXTENV };
  }).catch(function(E) {
    return ENV;
  });
}

