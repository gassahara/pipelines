// @proposal=P22 — the HYPERVISOR slice's persistent fields.
var HYPERVISORPERSISTENTFIELDS = {
  PROGRAMS: true,
  ROUTES: true
};

// @proposal=P22 — the HYPERVISOR slice's transient fields.
var HYPERVISORTRANSIENTFIELDS = {
  ENVBYPIPELINE: true,
  RENDERHTML: true,
  EXECUTIONSTACK: true,
  ACTIVEPIPELINES: true
};

function ENSUREHYPERVISORSLICE(ENV) {
  return ENSUREENVSLICE(ENV, 'hypervisor', function() {
    return {
      BOOT: true,
      ENVBYPIPELINE: {},
      RENDERHTML: '',
      EXECUTIONSTACK: [],
      ROUTES: {},
      ACTIVEPIPELINES: [],
      PROGRAMS: {}
    };
  });
}

// @proposal=P21 — sweep the HYPERVISOR slice before it is persisted.
function SWEEPHYPERVISORSLICE(SLICE) {
  if (!SLICE || typeof SLICE !== 'object') return SLICE;
  var OUT = {};
  Object.keys(SLICE).forEach(function(K) {
    if (HYPERVISORPERSISTENTFIELDS[K] === true) {
      OUT[K] = SLICE[K];
    }
  });
  return OUT;
}

function CREATEHYPERVISORERRORCONTEXT(LABEL) {
  return function(ERR) {
    if (!ERR) ERR = new Error('unknown hypervisor error');
    if (!ERR.DIAGNOSTIC) ERR.DIAGNOSTIC = {};
    ERR.DIAGNOSTIC.HYPERVISORSTAGE = LABEL;
    throw ERR;
  };
}

function REGISTERHYPERVISORPIPELINE(HYPERSLICE, PIPELINEID) {
  if (!HYPERSLICE.ACTIVEPIPELINES) HYPERSLICE.ACTIVEPIPELINES = HYPERSLICE.ACTIVEPIPELINES || [];
  if (HYPERSLICE.ACTIVEPIPELINES.indexOf(PIPELINEID) === -1) {
    HYPERSLICE.ACTIVEPIPELINES.push(PIPELINEID);
    SENDINSTRUCTION('WORLDMAPACTOR', MESSAGETYPES.UPDATE, {
      UPDATES: [{ PATH: 'HYPERVISOR', VALUE: HYPERSLICE }]
    }, GENERATETAG(), 'HYPERVISORACTOR');
  }
}

