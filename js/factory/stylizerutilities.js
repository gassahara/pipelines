/**
 * Removes redundant inherited inline style properties from child elements.
 * @param {string} html 
 * @returns {string} optimized HTML
 */
export function consolidateStyles(html) {
  const parser = new DOMParser();
  const doc = parser.parseFromString(html, 'text/html');
  const safeProps = new Set([
    'color', 'font-family', 'font-size', 'font-weight', 'font-style', 
    'line-height', 'text-align', 'cursor', 'letter-spacing', 'word-spacing'
  ]);
  
  function walk(el) {
    const children = Array.from(el.children);
    const parentStyle = el.style;
    for (const child of children) {
      if (!child.style) continue;
      const toRemove = [];
      for (let i = 0; i < child.style.length; i++) {
        const prop = child.style[i];
        if (safeProps.has(prop) && parentStyle[prop] === child.style[prop]) {
          toRemove.push(prop);
        }
      }
      for (const prop of toRemove) {
        child.style.removeProperty(prop);
      }
      walk(child);
    }
  }
  walk(doc.body);
  return doc.body.innerHTML;
}

