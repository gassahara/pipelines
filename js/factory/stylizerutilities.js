/**
 * Auto‑corrects text‑background contrast to meet WCAG AA (4.5:1).
 * Uses vector palette from colorutils to pick best replacement.
 * @param {string} html 
 * @param {number} minRatio 
 * @returns {string} corrected HTML
 */
export function verifyContrast(html, minRatio = 4.5) {
  const parser = new DOMParser();
  const doc = parser.parseFromString(html, 'text/html');
  
  function getEffectiveBackground(el) {
    let bg = el.style.backgroundColor;
    let parent = el.parentNode;
    while ((!bg || bg === 'transparent' || bg === '') && parent && parent !== doc) {
      if (parent.style) bg = parent.style.backgroundColor;
      parent = parent.parentNode;
    }
    return bg || '#ffffff';
  }
  
  function walk(el) {
    if (el.nodeType === 1 && el.textContent.trim()) {
      const color = el.style.color;
      const bg = getEffectiveBackground(el);
      if (color && bg) {
        const ratio = contrastRatio(color, bg);
        if (ratio < minRatio) {
          const palette = getContrastingPalette(bg, minRatio);
          if (palette.length > 0) {
            el.style.color = palette[0]; // least contrasting that still meets min
          } else {
            // fallback to computed foreground
            el.style.color = computeForeground(color, bg, minRatio);
          }
        }
      }
    }
    for (const child of el.children) {
      walk(child);
    }
  }
  walk(doc.body);
  return doc.body.innerHTML;
}

/**
 * Checks that text elements have visible font size, contrast, and line height.
 * @param {string} html 
 * @returns {object[]} violations
 */
export function verifyTextVisibility(html) {
  const violations = [];
  const parser = new DOMParser();
  const doc = parser.parseFromString(html, 'text/html');
  function walk(el) {
    if (el.nodeType === 1 && el.textContent.trim()) {
      const fontSize = parseFloat(el.style.fontSize) || 0;
      const lineHeight = parseFloat(el.style.lineHeight) || 0;
      const color = el.style.color;
      if (fontSize && fontSize < 12) {
        violations.push({ element: el.tagName + (el.id ? '#'+el.id : ''), issue: 'font-size too small', value: fontSize });
      }
      if (lineHeight && lineHeight < 1.2) {
        violations.push({ element: el.tagName + (el.id ? '#'+el.id : ''), issue: 'line-height too tight', value: lineHeight });
      }
      if (!color || color === 'transparent') {
        violations.push({ element: el.tagName + (el.id ? '#'+el.id : ''), issue: 'text color not set or transparent' });
      }
    }
    for (const child of el.children) walk(child);
  }
  walk(doc.body);
  return violations;
}

/**
 * Verifies buttons are visually distinct (size, contrast, cursor).
 * @param {string} html 
 * @returns {object[]} violations
 */
export function verifyButtonVisibility(html) {
  const violations = [];
  const parser = new DOMParser();
  const doc = parser.parseFromString(html, 'text/html');
  const buttons = doc.querySelectorAll('button, [role="button"], input[type="submit"], input[type="button"]');
  buttons.forEach(btn => {
    const width = parseFloat(btn.style.width) || 0;
    const height = parseFloat(btn.style.height) || 0;
    const fontSize = parseFloat(btn.style.fontSize) || 0;
    const cursor = btn.style.cursor;
    if (width < 44 || height < 44) {
      violations.push({ element: btn.tagName + (btn.id ? '#'+btn.id : ''), issue: 'touch target too small', w: width, h: height });
    }
    if (cursor !== 'pointer') {
      violations.push({ element: btn.tagName + (btn.id ? '#'+btn.id : ''), issue: 'cursor not pointer' });
    }
  });
  return violations;
}

/**
 * Scores harmony between adjacent elements (color harmony) and reports poor combinations.
 * Can optionally correct using harmonious palette.
 * @param {string} html 
 * @param {object} options { autoCorrect: boolean }
 * @returns {object} { html?, violations[] }
 */
export function verifyHarmony(html, options = {}) {
  const violations = [];
  const parser = new DOMParser();
  const doc = parser.parseFromString(html, 'text/html');
  const allElements = doc.querySelectorAll('*');
  allElements.forEach(el => {
    if (!el.textContent.trim()) return;
    const bg = el.style.backgroundColor;
    const color = el.style.color;
    if (bg && color) {
      const score = colorHarmonyScore(color, bg);
      if (score < 0.5) {
        violations.push({ element: el.tagName + (el.id ? '#'+el.id : ''), score, color, bg });
        if (options.autoCorrect) {
          const palette = getHarmoniousPalette(bg, 3, { scheme: 'analogous' });
          if (palette.length > 0) {
            el.style.color = palette[0];
          }
        }
      }
    }
  });
  return { html: options.autoCorrect ? doc.body.innerHTML : html, violations };
}

