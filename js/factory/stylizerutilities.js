/**
 * Parses a theme reference HTML and returns a map of tag names to their complete inline style objects.
 * The reference must contain one element per tag under #theme-reference.
 * @param {string} referenceHTML - HTML string generated by generateThemeReference
 * @returns {Object} { tagName: { styleProp: value, ... } }
 */
export function extractAllTagStyles(referenceHTML) {
  const parser = new DOMParser();
  const doc = parser.parseFromString(referenceHTML, 'text/html');
  const refRoot = doc.getElementById('theme-reference');
  if (!refRoot) return {};
  
  const map = {};
  const children = Array.from(refRoot.children);
  for (const el of children) {
    const tag = el.tagName.toLowerCase();
    const styleObj = {};
    for (let i = 0; i < el.style.length; i++) {
      const prop = el.style[i];
      styleObj[prop] = el.style[prop];
    }
    if (Object.keys(styleObj).length > 0) {
      map[tag] = styleObj;
    }
  }
  return map;
}

